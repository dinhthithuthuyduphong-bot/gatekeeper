ROOT = Path(__file__).resolve().parents[1]


def macros() -> dict[str, str]:
    text = (ROOT / "paper/numbers.tex").read_text(encoding="utf-8")
    return dict(re.findall(r"\\newcommand\{\\n([A-Za-z]+)\}\{(.*)\}", text))


N = macros()


def v(name: str) -> str:
    """A number from the paper, Vietnamese formatting (comma decimal, x10^e as superscript)."""
    s = N[name]
    m = re.fullmatch(r"\\ensuremath\{([-0-9.]+)\\times10\^\{(-?\d+)\}\}", s)
    if m:
        return f"{m[1].replace('.', ',')}·10<sup>{m[2].replace('-', '−')}</sup>"
    if re.fullmatch(r"-?[0-9]+(\.[0-9]+)?", s):
        return s.replace(".", ",").replace("-", "−")
    return html.escape(s)


def ci(name: str) -> str:
    return f"{v(name)} [{v(name + 'Lo')}; {v(name + 'Hi')}]"


def num(name: str) -> float:
    return float(N[name])


def commit() -> str:
    r = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT
    )
    return r.stdout.strip() or "?"


def fmt_int(x: int) -> str:
    return f"{x:,}".replace(",", ".")


def tokens() -> str:
    rows = []
    tu = json.loads((ROOT / "results/token_usage.json").read_text())
    tot = {"runs": 0, "tokens_in": 0, "tokens_cached": 0, "tokens_out": 0}
    for st in tu.values():
        for k in tot:
            tot[k] += st["total"][k]
    rows.append(
        (
            "Pilot G1 và xác nhận (lượt chạy agent)",
            fmt_int(tot["runs"]),
            fmt_int(tot["tokens_in"]),
            fmt_int(tot["tokens_cached"]),
            fmt_int(tot["tokens_out"]),
        )
    )
    for f, label in (
        ("sham_audit.json", "Audit quy lỗi, " + "Flash-Lite"),
        ("sham_audit_flash.json", "Audit quy lỗi, Flash"),
        ("sham_audit_pro.json", "Audit quy lỗi, Pro"),
        ("e2_selection.json", "Chọn rule XRepoSkill (E2)"),
    ):
        d = json.loads((ROOT / "results" / f).read_text())
        rows.append(
            (label, str(d.get("jobs", "—")), fmt_int(d["tokens_in"]), "—", fmt_int(d["tokens_out"]))
        )
    body = "".join(
        f"<tr><td>{a}</td><td class=n>{b}</td><td class=n>{c}</td><td class=n>{d}</td><td class=n>{e}</td></tr>"
        for a, b, c, d, e in rows
    )
    return body


def chart() -> str:
    """Resolved tasks out of 100 per condition, horizontal paired bars, one linear scale."""
    rows = [
        ("Jinja, lịch sử gốc", num("jinjaNone"), num("jinjaSkill")),
        ("Jinja, một commit", num("jinjaLFNone"), num("jinjaLFSkill")),
        ("Jinja, skill bỏ chỉ dẫn git", num("abNone"), num("abSkill")),
        ("Bleve, lịch sử gốc", num("bleveNone"), num("bleveSkill")),
        ("Bleve, một commit", num("bleveLFNone"), num("bleveLFSkill")),
        ("Pygments, dùng lại skill Jinja", num("pygNone"), num("pygSkill")),
    ]
    left, width, rh = 210, 330, 34
    h = 30 + rh * len(rows) + 24
    x = lambda val: left + width * val / 100  # noqa: E731
    out = [f'<svg viewBox="0 0 {left + width + 40} {h}" role="img" aria-label="Số task giải được">']
    for t in (0, 25, 50, 75, 100):
        out.append(f'<line class="gl" x1="{x(t):.1f}" x2="{x(t):.1f}" y1="18" y2="{h - 22}"/>')
        out.append(f'<text class="tick" x="{x(t):.1f}" y="{h - 6}" text-anchor="middle">{t}</text>')
    for i, (lab, a, b) in enumerate(rows):
        y = 26 + i * rh
        out.append(
            f'<text class="axis" x="{left - 10}" y="{y + 14}" text-anchor="end">{html.escape(lab)}</text>'
        )
        out.append(f'<rect class="b0" x="{left}" y="{y}" width="{x(a) - left:.1f}" height="11"/>')
        out.append(
            f'<rect class="b1" x="{left}" y="{y + 13}" width="{x(b) - left:.1f}" height="11"/>'
        )
        out.append(f'<text class="val" x="{x(a) + 4:.1f}" y="{y + 10}">{int(a)}</text>')
        out.append(f'<text class="val" x="{x(b) + 4:.1f}" y="{y + 23}">{int(b)}</text>')
    out.append("</svg>")
    return "".join(out)


