"""Build report/index.html: progress report for the advisor, in Vietnamese (0 USD).

  python scripts/build_report.py [--out report/index.html] [--fragment <path>]

Every number comes from paper/numbers.tex (generated by scripts/make_numbers.py from results/),
so the report and the paper cannot disagree; token counts come from results/token_usage.json and
the audit result files. `--fragment` also writes the page without the document skeleton (for
publishing as an artifact). Decimal separator: comma (Vietnamese convention).
"""

