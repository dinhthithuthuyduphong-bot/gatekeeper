"""Generate LaTeX tables for the paper from results/ (TODO.md Phase 7: 'Script tu sinh moi bang').

Numbers in the paper must come from these files, never typed by hand.
Writes paper/tables/*.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

OUT = Path("paper/tables")


def load(p: str):
    f = Path(p)
    return json.loads(f.read_text()) if f.exists() else None


def tex_escape(s: str) -> str:
    return (
        str(s)
        .replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
    )


def write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text(
        "% generated by scripts/make_tables.py -- do not edit\n" + body
    )
    print("wrote", OUT / f"{name}.tex")


def design_table(d: dict) -> str:
    effs = list(d["rows"][0]["trials"].keys())
    lines = [
        r"\begin{tabular}{rr" + "r" * len(effs) + "}",
        r"\toprule",
        r"$\theta$ & cells & " + " & ".join(f"STR $={e}$" for e in effs) + r" \\",
        r"\midrule",
    ]
    for r in d["rows"]:
        vals = [str(r["trials"][e]) if r["trials"][e] else f"$>${d['max_budget']}" for e in effs]
        lines.append(f"{r['theta']} & {r['cells']} & " + " & ".join(vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def power_table(d: dict) -> str:
    lines = [
        r"\begin{tabular}{rrrrr}",
        r"\toprule",
        r"& \multicolumn{2}{c}{lower bound $>5$ pts} & \multicolumn{2}{c}{superiority $>0$} \\",
        r"harmful pairs & indep. & nested & indep. & nested \\",
        r"\midrule",
    ]
    for r in d["rows"]:
        v = [
            r[k]
            for k in (
                "margin5_independent",
                "margin5_nested",
                "superiority_independent",
                "superiority_nested",
            )
        ]
        lines.append(f"{r['n_harmful']} & " + " & ".join(f"{x:.2f}" for x in v) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def sskb_table(d: dict) -> str:
    vc = d["variance_components"]["all"]
    es = d["effect_sizes"]
    cd = d["context_dependence"]
    rows = [
        (r"$\sigma_T^2$ (shared task difficulty)", f"{vc['sigma_T2']:.3f}"),
        (r"$\sigma_S^2$ (paired-difference noise)", f"{vc['sigma_S2']:.3f}"),
        (r"pairing saving $1+2\sigma_T^2/\sigma_S^2$", f"{vc['unpaired_over_paired']:.2f}"),
        ("paired differences exactly zero", f"{d['paired_differences']['frac_exactly_zero']:.2f}"),
        ("true SD of STR across cells", f"{es['estimated_true_sd']:.3f}"),
        (
            "cross-config / within-config reliability",
            f"{cd['mean_cross_config_r']:.2f} / {cd['mean_within_config_reliability']:.2f}",
        ),
    ]
    body = "\n".join(f"{a} & {b} \\\\" for a, b in rows)
    return (
        "\\begin{tabular}{lr}\n\\toprule\nquantity & value \\\\\n\\midrule\n"
        + body
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def main() -> None:
    if d := load("results/design_table.json"):
        write("design", design_table(d))
    if d := load("results/endpoint_power.json"):
        write("power", power_table(d))
    if d := load("results/sskb_analysis.json"):
        write("sskb", sskb_table(d))


if __name__ == "__main__":
    main()
